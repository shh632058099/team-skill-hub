import assert from "node:assert/strict";
import { test } from "node:test";
import {
  GitHubChangeRequestProvider,
  GitLabChangeRequestProvider,
} from "../src/expert-platform/git-change-request-provider.js";

const credentials = {
  "publish-token": { type: "https-token" as const, tokenEnv: "TEST_CHANGE_REQUEST_TOKEN" },
};

function input() {
  return {
    repositoryIdentity: "repo-1@7",
    headBranch: "tsh/work-a1",
    headCommit: "c".repeat(40),
    baseBranch: "main",
    title: "Fix worker publication",
    body: "Generated by Team Skill Hub",
    idempotencyKey: "publication:pub-1",
    credentialGrantRef: "publish-token",
  };
}

test("GitHub change request provider creates a PR and binds the pushed commit", async () => {
  const previous = process.env.TEST_CHANGE_REQUEST_TOKEN;
  process.env.TEST_CHANGE_REQUEST_TOKEN = "secret-token";
  try {
    const calls: Array<{ url: string; init?: RequestInit }> = [];
    const provider = new GitHubChangeRequestProvider(
      "https://github.com/example/project.git",
      credentials,
      async (url, init) => {
        calls.push({ url: String(url), init });
        return new Response(
          JSON.stringify({
            number: 17,
            html_url: "https://github.com/example/project/pull/17",
            state: "open",
            head: { sha: "c".repeat(40), ref: "tsh/work-a1" },
            base: { ref: "main" },
          }),
          { status: 201, headers: { "content-type": "application/json" } },
        );
      },
    );

    const result = await provider.create(input());
    assert.equal(result.provider, "github");
    assert.equal(result.externalId, "17");
    assert.equal(result.url, "https://github.com/example/project/pull/17");
    assert.equal(result.headCommit, "c".repeat(40));
    assert.equal(result.baseBranch, "main");
    assert.equal(calls.length, 1);
    assert.match(calls[0]!.url, /api\.github\.com\/repos\/example\/project\/pulls$/);
    assert.equal(calls[0]!.init?.method, "POST");
    assert.equal((calls[0]!.init?.headers as Record<string, string>).authorization, "Bearer secret-token");
  } finally {
    if (previous === undefined) delete process.env.TEST_CHANGE_REQUEST_TOKEN;
    else process.env.TEST_CHANGE_REQUEST_TOKEN = previous;
  }
});

test("GitHub change request provider recovers an existing PR after duplicate create", async () => {
  const previous = process.env.TEST_CHANGE_REQUEST_TOKEN;
  process.env.TEST_CHANGE_REQUEST_TOKEN = "secret-token";
  try {
    let count = 0;
    const provider = new GitHubChangeRequestProvider(
      "https://github.com/example/project.git",
      credentials,
      async (_url, init) => {
        count += 1;
        if (init?.method === "POST") return new Response("", { status: 422 });
        return new Response(
          JSON.stringify([
            {
              number: 18,
              html_url: "https://github.com/example/project/pull/18",
              state: "open",
              head: { sha: "c".repeat(40), ref: "tsh/work-a1" },
              base: { ref: "main" },
            },
          ]),
          { status: 200, headers: { "content-type": "application/json" } },
        );
      },
    );

    const result = await provider.create(input());
    assert.equal(result.externalId, "18");
    assert.equal(count, 2);
  } finally {
    if (previous === undefined) delete process.env.TEST_CHANGE_REQUEST_TOKEN;
    else process.env.TEST_CHANGE_REQUEST_TOKEN = previous;
  }
});

test("GitHub change request provider rejects a PR that is not bound to the pushed commit", async () => {
  const previous = process.env.TEST_CHANGE_REQUEST_TOKEN;
  process.env.TEST_CHANGE_REQUEST_TOKEN = "secret-token";
  try {
    const provider = new GitHubChangeRequestProvider(
      "https://github.com/example/project.git",
      credentials,
      async () =>
        new Response(
          JSON.stringify({
            number: 19,
            html_url: "https://github.com/example/project/pull/19",
            state: "open",
            head: { sha: "d".repeat(40), ref: "tsh/work-a1" },
            base: { ref: "main" },
          }),
          { status: 201, headers: { "content-type": "application/json" } },
        ),
    );

    await assert.rejects(() => provider.create(input()), /CHANGE_REQUEST_HEAD_MISMATCH/);
  } finally {
    if (previous === undefined) delete process.env.TEST_CHANGE_REQUEST_TOKEN;
    else process.env.TEST_CHANGE_REQUEST_TOKEN = previous;
  }
});

