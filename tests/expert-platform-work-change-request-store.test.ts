import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { test } from "node:test";
import { WorkChangeRequestStore } from "../src/expert-platform/work-change-request-store.js";

function fixture() {
  return {
    workItemId: "work-1",
    workAttemptId: "attempt-1",
    publicationId: "pub-1",
    ownerWorkerId: "worker-1",
    repositoryIdentity: "repo-1@7",
    repositoryUrl: "https://github.com/example/project.git",
    headBranch: "tsh/work-a1",
    headCommit: "c".repeat(40),
    baseBranch: "main",
    title: "Fix publication",
    body: "Generated by Team Skill Hub",
    idempotencyKey: "publication:pub-1",
    credentialGrantRef: "publish-token",
  };
}

test("change request intent persists and idempotent create reuses publication identity", () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "work-change-request-"));
  const file = path.join(dir, "runtime.sqlite");
  try {
    const store = new WorkChangeRequestStore(file);
    const first = store.createOrReuse(fixture(), 1000);
    const again = store.createOrReuse(fixture(), 1100);
    assert.equal(first.changeRequestId, again.changeRequestId);
    assert.equal(first.state, "pending");
    store.close();

    const reopened = new WorkChangeRequestStore(file);
    assert.equal(reopened.get(first.changeRequestId).headCommit, "c".repeat(40));
    reopened.close();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("change request claim is owner-affine, fenced and completes with exact commit binding", () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "work-change-request-claim-"));
  try {
    const store = new WorkChangeRequestStore(path.join(dir, "runtime.sqlite"));
    const record = store.createOrReuse(fixture(), 1000);
    assert.equal(store.claim("other-worker", 1100, 30_000), null);
    const claim = store.claim("worker-1", 1100, 30_000)!;
    assert.equal(claim.changeRequestId, record.changeRequestId);
    assert.equal(claim.fencing, 1);
    const created = store.complete(
      claim,
      {
        success: true,
        provider: "github",
        externalId: "17",
        url: "https://github.com/example/project/pull/17",
        headCommit: "c".repeat(40),
        baseBranch: "main",
      },
      1200,
    );
    assert.equal(created.state, "created");
    assert.equal(created.externalId, "17");
    assert.equal(created.url, "https://github.com/example/project/pull/17");
    assert.throws(
      () =>
        store.complete(
          claim,
          {
            success: true,
            provider: "github",
            externalId: "17",
            url: "https://github.com/example/project/pull/17",
            headCommit: "c".repeat(40),
            baseBranch: "main",
          },
          1300,
        ),
      /STALE_CHANGE_REQUEST_OPERATION/,
    );
    store.close();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

test("change request cancellation fences pending and creating operations", () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "work-change-request-cancel-"));
  try {
    const store = new WorkChangeRequestStore(path.join(dir, "runtime.sqlite"));
    const pending = store.createOrReuse(
      { ...fixture(), publicationId: "pub-pending", idempotencyKey: "publication:pub-pending" },
      1000,
    );
    const cancelledPending = store.cancelForWork("work-1", 1050);
    assert.ok(cancelledPending.cancelledChangeRequestIds.includes(pending.changeRequestId));
    assert.deepEqual(cancelledPending.outcomeUnknownChangeRequestIds, []);
    assert.equal(store.get(pending.changeRequestId).state, "blocked");
    assert.equal(store.get(pending.changeRequestId).lastErrorCode, "WORK_CANCELLED");

    const creating = store.createOrReuse(
      { ...fixture(), publicationId: "pub-creating", idempotencyKey: "publication:pub-creating" },
      1100,
    );
    const claim = store.claim("worker-1", 1200, 1000)!;
    assert.equal(claim.changeRequestId, creating.changeRequestId);
    const cancelledCreating = store.cancelForWork("work-1", 1250);
    assert.ok(cancelledCreating.outcomeUnknownChangeRequestIds.includes(creating.changeRequestId));
    assert.equal(store.get(creating.changeRequestId).state, "blocked");
    assert.equal(store.get(creating.changeRequestId).lastErrorCode, "WORK_CANCELLED_OUTCOME_UNKNOWN");
    assert.throws(
      () => store.complete(claim, { success: false, errorCode: "X" }, 1300),
      /STALE_CHANGE_REQUEST_OPERATION/,
    );
    store.close();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});

