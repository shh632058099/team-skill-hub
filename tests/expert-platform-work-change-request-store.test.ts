test("transient change request failures use durable bounded backoff", () => {
  const dir = mkdtempSync(path.join(os.tmpdir(), "work-change-request-retry-"));
  try {
    const store = new WorkChangeRequestStore(path.join(dir, "runtime.sqlite"));
    store.createOrReuse(fixture(), 1000);
    const first = store.claim("worker-1", 1100, 1000)!;
    const retry1 = store.complete(first, { success: false, errorCode: "CHANGE_REQUEST_CREATE_FAILED" }, 1200);
    assert.equal(retry1.state, "pending");
    assert.equal(retry1.retryCount, 1);
    assert.equal(retry1.nextAttemptAt, 2200);
    assert.equal(store.claim("worker-1", 2199, 1000), null);

    const second = store.claim("worker-1", 2200, 1000)!;
    const retry2 = store.complete(second, { success: false, errorCode: "CHANGE_REQUEST_CREATE_FAILED" }, 2300);
    assert.equal(retry2.retryCount, 2);
    assert.equal(retry2.nextAttemptAt, 7300);

    const third = store.claim("worker-1", 7300, 1000)!;
    const blocked = store.complete(third, { success: false, errorCode: "CHANGE_REQUEST_CREATE_FAILED" }, 7400);
    assert.equal(blocked.state, "blocked");
    assert.equal(blocked.retryCount, 3);
    store.close();
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
});
