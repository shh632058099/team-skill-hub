#!/usr/bin/env python3
"""Inject Claude Code's actual session_id into Team Skill Hub task submissions.

Claude PreToolUse hook: reads one JSON object from stdin, emits updatedInput only
for the two Expert submission tools. Does not approve or deny permissions.
"""
import json
import hashlib
import hmac
import os
from pathlib import Path
import time
import re
import sys
import uuid

TOOL = re.compile(r"^mcp__teamSkillHub__(?:submit_expert_task_auto|submit_expert_task)$")


def main() -> None:
    try:
        payload = json.load(sys.stdin)
        if not isinstance(payload, dict) or payload.get("hook_event_name") != "PreToolUse":
            return
        if not isinstance(payload.get("tool_name"), str) or not TOOL.fullmatch(payload["tool_name"]):
            return
        provided = payload.get("session_id")
        if not isinstance(provided, str):
            return
        session_id = str(uuid.UUID(provided))
        if provided.lower() != session_id:
            return
        tool_input = payload.get("tool_input")
        if not isinstance(tool_input, dict):
            return
        # Use the authenticated local Claude hook's session identity rather than
        # relying on anything the model may put in the request.
        updated = dict(tool_input)
        updated["clientSessionId"] = session_id
        # The signature is generated by the hook, not the model. Never emit a
        # model-supplied proof if the credential is unavailable.
        updated.pop("clientSessionProof", None)
        config_path = Path(os.environ.get("TEAM_SKILL_HUB_HOOK_CONFIG") or
                           Path(__file__).resolve().parent / "team-skill-hub.conf")
        key_env = "TEAM_SKILL_HUB_API_KEY"
        if config_path.is_file():
            for line in config_path.read_text(encoding="utf-8").splitlines():
                if line.startswith("api_key_env="):
                    candidate = line.partition("=")[2].strip()
                    if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", candidate):
                        key_env = candidate
        credential = os.environ.get(key_env, "")
        key = tool_input.get("idempotencyKey")
        if credential and isinstance(key, str):
            timestamp = str(int(time.time() * 1000))
            message = f"team-skill-hub/client-session/v1\n{session_id}\n{key}\n{timestamp}"
            signature = hmac.new(credential.encode(), message.encode(), hashlib.sha256).hexdigest()
            updated["clientSessionProof"] = f"{timestamp}.{signature}"
        print(json.dumps({"hookSpecificOutput": {
            "hookEventName": "PreToolUse",
            "updatedInput": updated
        }}, ensure_ascii=False))
    except (ValueError, TypeError, json.JSONDecodeError):
        # A malformed hook must not block unrelated Claude functionality.
        return


if __name__ == "__main__":
    main()
